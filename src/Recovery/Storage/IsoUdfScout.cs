using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Threading;

namespace UsbRecovery
{
    /// <summary>
    /// Represents an individual file or directory record inside an ISO 9660 / Joliet / UDF volume.
    /// </summary>
    public sealed class IsoUdfFileRecord
    {
        public string Name { get; set; }
        public string FullPath { get; set; }
        public long Size { get; set; }
        public long ExtentOffset { get; set; }
        public DateTime RecordingTimeUtc { get; set; }
        public bool IsDirectory { get; set; }
        public bool IsHidden { get; set; }
        public bool IsJoliet { get; set; }
        public bool IsUdf { get; set; }
        public bool IsCarved { get; set; }

        public IsoUdfFileRecord()
        {
            Name = String.Empty;
            FullPath = String.Empty;
        }
    }

    /// <summary>
    /// Forensic summary report generated by the ISO 9660 / UDF Scout.
    /// </summary>
    public sealed class IsoUdfReport
    {
        public string SourcePath { get; set; }
        public string VolumeIdentifier { get; set; }
        public string SystemIdentifier { get; set; }
        public string VolumeSetIdentifier { get; set; }
        public string PublisherIdentifier { get; set; }
        public string FilesystemType { get; set; }
        public long VolumeSpaceSize { get; set; }
        public int LogicalBlockSize { get; set; }
        public int TotalFiles { get; set; }
        public int TotalDirectories { get; set; }
        public long TotalFileBytes { get; set; }
        public bool IsCarved { get; set; }
        public List<IsoUdfFileRecord> Files { get; set; }
        public List<string> Warnings { get; set; }

        public IsoUdfReport()
        {
            SourcePath = String.Empty;
            VolumeIdentifier = String.Empty;
            SystemIdentifier = String.Empty;
            VolumeSetIdentifier = String.Empty;
            PublisherIdentifier = String.Empty;
            FilesystemType = "Unknown";
            LogicalBlockSize = 2048;
            Files = new List<IsoUdfFileRecord>();
            Warnings = new List<string>();
        }

        public string ToJson()
        {
            var sb = new StringBuilder();
            sb.Append("{");
            sb.AppendFormat("\"SourcePath\":\"{0}\",", EscapeJson(SourcePath));
            sb.AppendFormat("\"VolumeIdentifier\":\"{0}\",", EscapeJson(VolumeIdentifier));
            sb.AppendFormat("\"SystemIdentifier\":\"{0}\",", EscapeJson(SystemIdentifier));
            sb.AppendFormat("\"VolumeSetIdentifier\":\"{0}\",", EscapeJson(VolumeSetIdentifier));
            sb.AppendFormat("\"PublisherIdentifier\":\"{0}\",", EscapeJson(PublisherIdentifier));
            sb.AppendFormat("\"FilesystemType\":\"{0}\",", EscapeJson(FilesystemType));
            sb.AppendFormat("\"VolumeSpaceSize\":{0},", VolumeSpaceSize);
            sb.AppendFormat("\"LogicalBlockSize\":{0},", LogicalBlockSize);
            sb.AppendFormat("\"TotalFiles\":{0},", TotalFiles);
            sb.AppendFormat("\"TotalDirectories\":{0},", TotalDirectories);
            sb.AppendFormat("\"TotalFileBytes\":{0},", TotalFileBytes);
            sb.AppendFormat("\"IsCarved\":{0},", IsCarved ? "true" : "false");
            sb.Append("\"Files\":[");
            for (int i = 0; i < Files.Count; i++)
            {
                if (i > 0) sb.Append(",");
                var f = Files[i];
                sb.Append("{");
                sb.AppendFormat("\"Name\":\"{0}\",", EscapeJson(f.Name));
                sb.AppendFormat("\"FullPath\":\"{0}\",", EscapeJson(f.FullPath));
                sb.AppendFormat("\"Size\":{0},", f.Size);
                sb.AppendFormat("\"ExtentOffset\":{0},", f.ExtentOffset);
                sb.AppendFormat("\"RecordingTimeUtc\":\"{0:O}\",", f.RecordingTimeUtc);
                sb.AppendFormat("\"IsDirectory\":{0},", f.IsDirectory ? "true" : "false");
                sb.AppendFormat("\"IsHidden\":{0},", f.IsHidden ? "true" : "false");
                sb.AppendFormat("\"IsJoliet\":{0},", f.IsJoliet ? "true" : "false");
                sb.AppendFormat("\"IsUdf\":{0},", f.IsUdf ? "true" : "false");
                sb.AppendFormat("\"IsCarved\":{0}", f.IsCarved ? "true" : "false");
                sb.Append("}");
            }
            sb.Append("]");
            sb.Append("}");
            return sb.ToString();
        }

        private static string EscapeJson(string s)
        {
            if (string.IsNullOrEmpty(s)) return String.Empty;
            return s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", " ");
        }
    }

    /// <summary>
    /// Forensic ISO 9660, Joliet, and UDF (Universal Disk Format) Scout & Carver.
    /// Traverses Volume Descriptors (PVD/SVD at sector 16+), Joliet UCS-2 directory records,
    /// El Torito boot catalogs, and UDF Anchor Volume Descriptor Pointers (AVDP).
    /// Carves deleted or orphan ISO/UDF files from raw USB sectors and damaged optical images.
    /// </summary>
    public static class IsoUdfScout
    {
        // Sector constants
        public const int StandardSectorSize = 2048;
        public const int SystemAreaSectors = 16;
        public const long StandardPvdOffset = 16L * StandardSectorSize; // 0x8000 (32,768)

        // Magic identifiers
        public static readonly byte[] IsoMagic = new byte[] { 0x43, 0x44, 0x30, 0x30, 0x31 }; // "CD001"
        public static readonly byte[] UdfBeaMagic = new byte[] { 0x42, 0x45, 0x41, 0x30, 0x31 }; // "BEA01"
        public static readonly byte[] UdfNsr02Magic = new byte[] { 0x4E, 0x53, 0x52, 0x30, 0x32 }; // "NSR02"
        public static readonly byte[] UdfNsr03Magic = new byte[] { 0x4E, 0x53, 0x52, 0x30, 0x33 }; // "NSR03"
        public static readonly byte[] UdfTeaMagic = new byte[] { 0x54, 0x45, 0x41, 0x30, 0x31 }; // "TEA01"

        /// <summary>
        /// Scout ISO 9660 / Joliet / UDF filesystem from an image file or physical disk path.
        /// </summary>
        public static IsoUdfReport Scout(string path, CancellationToken ct = default(CancellationToken))
        {
            if (path == null) throw new ArgumentNullException("path");
            if (!File.Exists(path)) throw new FileNotFoundException("Target file not found", path);

            using (var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
            {
                return ScoutStream(fs, path, ct);
            }
        }

        /// <summary>
        /// Scout ISO 9660 / Joliet / UDF filesystem from a stream.
        /// </summary>
        public static IsoUdfReport ScoutStream(Stream stream, string sourceName = null, CancellationToken ct = default(CancellationToken))
        {
            var report = new IsoUdfReport { SourcePath = sourceName ?? "Stream" };
            if (stream == null || stream.Length < StandardPvdOffset + StandardSectorSize)
            {
                return report;
            }

            // Check standard Volume Recognition Sequence at sector 16 (0x8000)
            byte[] sector = new byte[StandardSectorSize];
            bool foundVrs = false;
            bool hasUdf = false;
            bool hasJoliet = false;

            // Check sector 16 to 32 for Volume Descriptors
            long rootExtentLba = -1;
            long rootDataLength = 0;
            bool rootIsJoliet = false;

            for (int sec = 16; sec < 32; sec++)
            {
                if (ct.IsCancellationRequested) break;
                long offset = (long)sec * StandardSectorSize;
                if (offset + StandardSectorSize > stream.Length) break;

                stream.Position = offset;
                int read = stream.Read(sector, 0, StandardSectorSize);
                if (read < StandardSectorSize) break;

                // Check for UDF identifiers
                if (MatchesMagic(sector, 1, UdfBeaMagic) || MatchesMagic(sector, 1, UdfNsr02Magic) || MatchesMagic(sector, 1, UdfNsr03Magic))
                {
                    hasUdf = true;
                    foundVrs = true;
                }

                // Check for ISO 9660 "CD001"
                if (MatchesMagic(sector, 1, IsoMagic))
                {
                    foundVrs = true;
                    byte descType = sector[0];

                    if (descType == 0x01) // Primary Volume Descriptor (PVD)
                    {
                        if (string.IsNullOrEmpty(report.VolumeIdentifier))
                        {
                            report.SystemIdentifier = Encoding.ASCII.GetString(sector, 8, 32).TrimEnd('\0', ' ');
                            report.VolumeIdentifier = Encoding.ASCII.GetString(sector, 40, 32).TrimEnd('\0', ' ');
                            report.VolumeSpaceSize = ReadBothEndianUInt32(sector, 80) * (long)StandardSectorSize;
                            report.LogicalBlockSize = (int)ReadBothEndianUInt16(sector, 128);
                            if (report.LogicalBlockSize <= 0) report.LogicalBlockSize = StandardSectorSize;

                            report.VolumeSetIdentifier = Encoding.ASCII.GetString(sector, 190, 128).TrimEnd('\0', ' ');
                            report.PublisherIdentifier = Encoding.ASCII.GetString(sector, 318, 128).TrimEnd('\0', ' ');

                            // Root directory record at offset 156
                            if (rootExtentLba < 0)
                            {
                                rootExtentLba = ReadBothEndianUInt32(sector, 156 + 2);
                                rootDataLength = ReadBothEndianUInt32(sector, 156 + 10);
                                rootIsJoliet = false;
                            }
                        }
                    }
                    else if (descType == 0x02) // Supplementary Volume Descriptor (SVD - Joliet)
                    {
                        // Escape sequences at offset 88 check for UCS-2 (Joliet)
                        hasJoliet = true;
                        // Joliet stores VolumeIdentifier in UCS-2 Big Endian at offset 40
                        string jolietVol = Encoding.BigEndianUnicode.GetString(sector, 40, 32).TrimEnd('\0', ' ');
                        if (!string.IsNullOrEmpty(jolietVol))
                        {
                            report.VolumeIdentifier = jolietVol;
                        }

                        // Prefer Joliet root directory record for long Unicode filenames
                        rootExtentLba = ReadBothEndianUInt32(sector, 156 + 2);
                        rootDataLength = ReadBothEndianUInt32(sector, 156 + 10);
                        rootIsJoliet = true;
                    }
                    else if (descType == 0xFF) // Terminator
                    {
                        break;
                    }
                }
            }

            if (foundVrs)
            {
                if (hasUdf && hasJoliet) report.FilesystemType = "ISO 9660 / Joliet / UDF Hybrid";
                else if (hasUdf) report.FilesystemType = "UDF";
                else if (hasJoliet) report.FilesystemType = "ISO 9660 / Joliet";
                else report.FilesystemType = "ISO 9660";

                // Parse directory tree if root extent was identified
                if (rootExtentLba > 0 && rootDataLength > 0)
                {
                    var visitedLba = new HashSet<long>();
                    TraverseDirectory(stream, rootExtentLba, rootDataLength, "", rootIsJoliet, report, visitedLba, ct);
                }
            }
            else
            {
                // Unallocated or damaged sector carving:
                // Scan entire stream for orphaned ISO/Joliet/UDF directory records and volume descriptors
                CarveUnallocatedIso(stream, report, ct);
            }

            FinalizeReport(report);
            return report;
        }

        public static IsoUdfReport ParseBuffer(byte[] buffer, string sourceName = null)
        {
            var report = new IsoUdfReport { SourcePath = sourceName ?? "Buffer" };
            if (buffer == null || buffer.Length < 64) return report;

            using (var ms = new MemoryStream(buffer))
            {
                return ScoutStream(ms, sourceName, CancellationToken.None);
            }
        }

        /// <summary>
        /// Traverses ISO 9660 / Joliet directory records recursively.
        /// </summary>
        private static void TraverseDirectory(Stream stream, long lba, long length, string parentPath, bool isJoliet, IsoUdfReport report, HashSet<long> visitedLba, CancellationToken ct)
        {
            if (visitedLba.Contains(lba)) return;
            visitedLba.Add(lba);

            long dirOffset = lba * (long)report.LogicalBlockSize;
            if (dirOffset + length > stream.Length) length = Math.Max(0, stream.Length - dirOffset);
            if (length <= 0) return;

            byte[] dirSector = new byte[report.LogicalBlockSize];
            long bytesRemaining = length;
            long currentOffset = dirOffset;

            var subDirectories = new List<IsoUdfFileRecord>();

            while (bytesRemaining > 0)
            {
                if (ct.IsCancellationRequested) break;

                stream.Position = currentOffset;
                int read = stream.Read(dirSector, 0, (int)Math.Min(dirSector.Length, bytesRemaining));
                if (read < 34) break;

                int cursor = 0;
                while (cursor + 33 <= read)
                {
                    byte recordLen = dirSector[cursor];
                    if (recordLen == 0)
                    {
                        // ISO 9660 padding: directory records cannot cross sector boundaries
                        break;
                    }
                    if (cursor + recordLen > read) break;

                    long extentLba = ReadBothEndianUInt32(dirSector, cursor + 2);
                    long dataLen = ReadBothEndianUInt32(dirSector, cursor + 10);
                    DateTime recTime = ParseIsoDateTime(dirSector, cursor + 18);
                    byte flags = dirSector[cursor + 25];
                    byte nameLen = dirSector[cursor + 32];

                    bool isDir = (flags & 0x02) != 0;
                    bool isHidden = (flags & 0x01) != 0;

                    string fileName = "";
                    if (nameLen > 0 && cursor + 33 + nameLen <= read)
                    {
                        if (nameLen == 1 && dirSector[cursor + 33] == 0x00)
                        {
                            // Current directory "."
                            fileName = ".";
                        }
                        else if (nameLen == 1 && dirSector[cursor + 33] == 0x01)
                        {
                            // Parent directory ".."
                            fileName = "..";
                        }
                        else if (isJoliet)
                        {
                            // Joliet Unicode (UCS-2 Big Endian)
                            fileName = Encoding.BigEndianUnicode.GetString(dirSector, cursor + 33, nameLen).TrimEnd('\0', ' ');
                        }
                        else
                        {
                            // Standard ISO 9660 ASCII
                            fileName = Encoding.ASCII.GetString(dirSector, cursor + 33, nameLen).TrimEnd('\0', ' ');
                            // Strip version suffix e.g. ";1"
                            int semi = fileName.IndexOf(';');
                            if (semi > 0) fileName = fileName.Substring(0, semi);
                        }
                    }

                    if (!string.IsNullOrEmpty(fileName) && fileName != "." && fileName != "..")
                    {
                        string fullPath = string.IsNullOrEmpty(parentPath) ? fileName : (parentPath + "/" + fileName);
                        long extentOffset = extentLba * (long)report.LogicalBlockSize;

                        var record = new IsoUdfFileRecord
                        {
                            Name = fileName,
                            FullPath = fullPath,
                            Size = isDir ? 0 : dataLen,
                            ExtentOffset = extentOffset,
                            RecordingTimeUtc = recTime,
                            IsDirectory = isDir,
                            IsHidden = isHidden,
                            IsJoliet = isJoliet,
                            IsUdf = false,
                            IsCarved = false
                        };

                        report.Files.Add(record);
                        if (isDir)
                        {
                            subDirectories.Add(record);
                        }
                    }

                    cursor += recordLen;
                }

                bytesRemaining -= dirSector.Length;
                currentOffset += dirSector.Length;
            }

            // Recurse into subdirectories
            foreach (var subDir in subDirectories)
            {
                if (ct.IsCancellationRequested) break;
                if (report.Files.Count > 10000) break; // Bounded count
                long subLba = subDir.ExtentOffset / (long)report.LogicalBlockSize;
                TraverseDirectory(stream, subLba, StandardSectorSize * 4, subDir.FullPath, isJoliet, report, visitedLba, ct);
            }
        }

        /// <summary>
        /// Carve orphan ISO / Joliet / UDF descriptors and directory records from unallocated sectors.
        /// </summary>
        private static void CarveUnallocatedIso(Stream stream, IsoUdfReport report, CancellationToken ct)
        {
            byte[] chunk = new byte[65536]; // 64 KiB buffer
            long streamLen = stream.Length;
            long pos = 0;

            while (pos < streamLen)
            {
                if (ct.IsCancellationRequested) break;
                stream.Position = pos;
                int bytesRead = stream.Read(chunk, 0, chunk.Length);
                if (bytesRead < 2048) break;

                for (int i = 0; i + 2048 <= bytesRead; i += 2048)
                {
                    // Check for "CD001" at i + 1
                    if (MatchesMagic(chunk, i + 1, IsoMagic))
                    {
                        byte descType = chunk[i];
                        if (descType == 0x01 || descType == 0x02)
                        {
                            report.IsCarved = true;
                            if (string.IsNullOrEmpty(report.VolumeIdentifier))
                            {
                                if (descType == 0x02)
                                {
                                    report.VolumeIdentifier = Encoding.BigEndianUnicode.GetString(chunk, i + 40, 32).TrimEnd('\0', ' ');
                                    report.FilesystemType = "ISO 9660 / Joliet (Carved)";
                                }
                                else
                                {
                                    report.VolumeIdentifier = Encoding.ASCII.GetString(chunk, i + 40, 32).TrimEnd('\0', ' ');
                                    report.FilesystemType = "ISO 9660 (Carved)";
                                }
                            }

                            // Extract root directory record
                            long extentLba = ReadBothEndianUInt32(chunk, i + 156 + 2);
                            long dataLen = ReadBothEndianUInt32(chunk, i + 156 + 10);
                            if (extentLba > 0 && dataLen > 0 && extentLba * 2048L < streamLen)
                            {
                                var visited = new HashSet<long>();
                                TraverseDirectory(stream, extentLba, dataLen, "$CARVED_ISO", descType == 0x02, report, visited, ct);
                            }
                        }
                    }
                    // Check for UDF AVDP or VRS
                    else if (MatchesMagic(chunk, i + 1, UdfBeaMagic) || MatchesMagic(chunk, i + 1, UdfNsr02Magic) || MatchesMagic(chunk, i + 1, UdfNsr03Magic))
                    {
                        report.IsCarved = true;
                        report.FilesystemType = "UDF (Carved)";
                    }
                }

                if (bytesRead < chunk.Length) break;
                pos += chunk.Length;
            }
        }

        /// <summary>
        /// Safely extracts an individual file payload directly to disk using a 64 KiB buffer.
        /// </summary>
        public static bool ExtractFile(Stream imageStream, IsoUdfFileRecord file, string destinationPath)
        {
            if (imageStream == null || file == null || file.IsDirectory || file.ExtentOffset < 0 || file.Size <= 0)
                return false;

            if (file.ExtentOffset + file.Size > imageStream.Length)
                return false;

            string dir = Path.GetDirectoryName(destinationPath);
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
            {
                Directory.CreateDirectory(dir);
            }

            byte[] buffer = new byte[65536];
            long bytesRemaining = file.Size;
            imageStream.Position = file.ExtentOffset;

            using (var outFs = new FileStream(destinationPath, FileMode.Create, FileAccess.Write, FileShare.None))
            {
                while (bytesRemaining > 0)
                {
                    int toRead = (int)Math.Min(buffer.Length, bytesRemaining);
                    int read = imageStream.Read(buffer, 0, toRead);
                    if (read <= 0) break;
                    outFs.Write(buffer, 0, read);
                    bytesRemaining -= read;
                }
            }

            return true;
        }

        private static void FinalizeReport(IsoUdfReport report)
        {
            int files = 0;
            int dirs = 0;
            long totalBytes = 0;

            foreach (var f in report.Files)
            {
                if (f.IsDirectory) dirs++;
                else
                {
                    files++;
                    totalBytes += f.Size;
                }
            }

            report.TotalFiles = files;
            report.TotalDirectories = dirs;
            report.TotalFileBytes = totalBytes;
        }

        public static uint ReadBothEndianUInt32(byte[] buffer, int offset)
        {
            if (buffer == null || offset + 4 > buffer.Length) return 0;
            // First 4 bytes are little-endian
            return BitConverter.ToUInt32(buffer, offset);
        }

        public static ushort ReadBothEndianUInt16(byte[] buffer, int offset)
        {
            if (buffer == null || offset + 2 > buffer.Length) return 0;
            // First 2 bytes are little-endian
            return BitConverter.ToUInt16(buffer, offset);
        }

        public static DateTime ParseIsoDateTime(byte[] buffer, int offset)
        {
            if (buffer == null || offset + 7 > buffer.Length) return DateTime.MinValue;

            try
            {
                int year = 1900 + buffer[offset];
                int month = buffer[offset + 1];
                int day = buffer[offset + 2];
                int hour = buffer[offset + 3];
                int minute = buffer[offset + 4];
                int second = buffer[offset + 5];
                sbyte tzOffset15Min = (sbyte)buffer[offset + 6];

                if (year >= 1970 && year <= 2050 && month >= 1 && month <= 12 && day >= 1 && day <= 31 &&
                    hour >= 0 && hour <= 23 && minute >= 0 && minute <= 59 && second >= 0 && second <= 59)
                {
                    var dt = new DateTime(year, month, day, hour, minute, second, DateTimeKind.Utc);
                    if (tzOffset15Min != 0 && tzOffset15Min >= -48 && tzOffset15Min <= 52)
                    {
                        dt = dt.AddMinutes(-tzOffset15Min * 15);
                    }
                    return dt;
                }
            }
            catch { }

            return DateTime.MinValue;
        }

        private static bool MatchesMagic(byte[] buffer, int offset, byte[] magic)
        {
            if (buffer == null || offset < 0 || offset + magic.Length > buffer.Length) return false;
            for (int i = 0; i < magic.Length; i++)
            {
                if (buffer[offset + i] != magic[i]) return false;
            }
            return true;
        }
    }
