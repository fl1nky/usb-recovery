    /// <summary>
    /// Represents an individual block mapping in a Volume Shadow Copy (VSS) store.
    /// Maps a logical offset on the original volume to the physical offset in the VSS store.
    /// </summary>
    public sealed class VssBlockMapping
    {
        public long OriginalVolumeOffset { get; set; }
        public long StoreOffset { get; set; }
        public int BlockLength { get; set; }
        public uint Flags { get; set; }

        public VssBlockMapping()
        {
            BlockLength = 16384; // 16 KiB default
        }
    }

    /// <summary>
    /// Represents an individual Volume Shadow Copy (snapshot) record.
    /// </summary>
    public sealed class VssSnapshotRecord
    {
        public Guid SnapshotId { get; set; }
        public Guid SnapshotSetId { get; set; }
        public DateTime CreationTimeUtc { get; set; }
        public long VolumeSize { get; set; }
        public long AllocatedBytes { get; set; }
        public int StoreBlockCount { get; set; }
        public string MachineName { get; set; }
        public string Attributes { get; set; }
        public bool IsCarved { get; set; }
        public List<VssBlockMapping> BlockMappings { get; set; }

        public VssSnapshotRecord()
        {
            MachineName = String.Empty;
            Attributes = String.Empty;
            BlockMappings = new List<VssBlockMapping>();
        }
    }

    /// <summary>
    /// Summary report generated by the VSS Scout.
    /// </summary>
    public sealed class VssReport
    {
        public string SourcePath { get; set; }
        public int TotalSnapshots { get; set; }
        public int TotalStoreBlocks { get; set; }
        public long TotalSnapshotBytes { get; set; }
        public bool IsWipedOrOrphaned { get; set; }
        public string SuspicionReason { get; set; }
        public List<VssSnapshotRecord> Snapshots { get; set; }
        public List<string> Warnings { get; set; }

        public VssReport()
        {
            SourcePath = String.Empty;
            SuspicionReason = String.Empty;
            Snapshots = new List<VssSnapshotRecord>();
            Warnings = new List<string>();
        }

        public string ToJson()
        {
            var sb = new StringBuilder();
            sb.Append("{");
            sb.AppendFormat("\"SourcePath\":\"{0}\",", EscapeJson(SourcePath));
            sb.AppendFormat("\"TotalSnapshots\":{0},", TotalSnapshots);
            sb.AppendFormat("\"TotalStoreBlocks\":{0},", TotalStoreBlocks);
            sb.AppendFormat("\"TotalSnapshotBytes\":{0},", TotalSnapshotBytes);
            sb.AppendFormat("\"IsWipedOrOrphaned\":{0},", IsWipedOrOrphaned ? "true" : "false");
            sb.AppendFormat("\"SuspicionReason\":\"{0}\",", EscapeJson(SuspicionReason));
            sb.Append("\"Snapshots\":[");
            for (int i = 0; i < Snapshots.Count; i++)
            {
                if (i > 0) sb.Append(",");
                var s = Snapshots[i];
                sb.Append("{");
                sb.AppendFormat("\"SnapshotId\":\"{0}\",", s.SnapshotId);
                sb.AppendFormat("\"SnapshotSetId\":\"{0}\",", s.SnapshotSetId);
                sb.AppendFormat("\"CreationTimeUtc\":\"{0:O}\",", s.CreationTimeUtc);
                sb.AppendFormat("\"VolumeSize\":{0},", s.VolumeSize);
                sb.AppendFormat("\"AllocatedBytes\":{0},", s.AllocatedBytes);
                sb.AppendFormat("\"StoreBlockCount\":{0},", s.StoreBlockCount);
                sb.AppendFormat("\"MachineName\":\"{0}\",", EscapeJson(s.MachineName));
                sb.AppendFormat("\"Attributes\":\"{0}\",", EscapeJson(s.Attributes));
                sb.AppendFormat("\"IsCarved\":{0},", s.IsCarved ? "true" : "false");
                sb.AppendFormat("\"BlockMappingsCount\":{0}", s.BlockMappings.Count);
                sb.Append("}");
            }
            sb.Append("]");
            sb.Append("}");
            return sb.ToString();
        }

        private static string EscapeJson(string s)
        {
            if (string.IsNullOrEmpty(s)) return String.Empty;
            return s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", " ");
        }
    }

    /// <summary>
    /// Forensic Volume Shadow Copies (VSS) Scout & Snapshot Carver.
    /// Discovers VSS Store and Catalog blocks ({3808876b-c176-4e48-b7ae-04046e6cc752}),
    /// traverses snapshot entries, reconstructs Copy-on-Write (CoW) block descriptor tables,
    /// and flags anti-forensics snapshot deletion (T1490 Inhibit System Recovery).
    /// </summary>
    public static class VssScout
    {
        // Standard VSS Store Header identifier: {3808876b-c176-4e48-b7ae-04046e6cc752}
        // In little-endian byte representation:
        public static readonly byte[] VssIdentifierGuid = new byte[]
        {
            0x6B, 0x87, 0x08, 0x38,
            0x76, 0xC1,
            0x48, 0x4E,
            0xB7, 0xAE,
            0x04, 0x04, 0x6E, 0x6C, 0xC7, 0x52
        };

        // Magic "VSST" (Volume Shadow Storage Table)
        public static readonly byte[] VssTableMagic = new byte[] { 0x56, 0x53, 0x53, 0x54 };

        // 2006-01-01 FILETIME: ~127806528000000000L
        // 2035-01-01 FILETIME: ~136975200000000000L
        private const long MinValidFileTime = 127806528000000000L;
        private const long MaxValidFileTime = 136975200000000000L;

        /// <summary>
        /// Scout VSS artifacts from a disk image, volume, or System Volume Information directory.
        /// </summary>
        public static VssReport Scout(string path, CancellationToken ct = default(CancellationToken))
        {
            if (path == null) throw new ArgumentNullException("path");

            var report = new VssReport { SourcePath = path };

            if (Directory.Exists(path))
            {
                return ScoutDirectory(path, ct);
            }

            if (!File.Exists(path))
            {
                throw new FileNotFoundException("Target path not found", path);
            }

            using (var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
            {
                return ScoutStream(fs, path, ct);
            }
        }

        public static VssReport ScoutDirectory(string dirPath, CancellationToken ct = default(CancellationToken))
        {
            var report = new VssReport { SourcePath = dirPath };

            try
            {
                // Look for System Volume Information files matching {GUID}{3808876b-c176-4e48-b7ae-04046e6cc752}
                var files = Directory.GetFiles(dirPath, "*3808876b-c176-4e48-b7ae-04046e6cc752*", SearchOption.AllDirectories);
                if (files.Length > 0)
                {
                    foreach (var file in files)
                    {
                        if (ct.IsCancellationRequested) break;
                        try
                        {
                            using (var fs = new FileStream(file, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
                            {
                                var rep = ScoutStream(fs, file, ct);
                                if (rep != null && rep.Snapshots.Count > 0)
                                {
                                    report.Snapshots.AddRange(rep.Snapshots);
                                    report.TotalStoreBlocks += rep.TotalStoreBlocks;
                                }
                            }
                        }
                        catch (Exception ex)
                        {
                            report.Warnings.Add("Failed to parse " + Path.GetFileName(file) + ": " + ex.Message);
                        }
                    }
                }
                else
                {
                    report.Warnings.Add("No VSS catalog files found in directory.");
                }
            }
            catch (Exception ex)
            {
                report.Warnings.Add("Error scanning directory: " + ex.Message);
            }

            FinalizeReport(report);
            return report;
        }

        public static VssReport ScoutStream(Stream stream, string sourceName = null, CancellationToken ct = default(CancellationToken))
        {
            var report = new VssReport { SourcePath = sourceName ?? "Stream" };
            if (stream == null || stream.Length < 128) return report;

            long streamLength = stream.Length;
            byte[] buffer = new byte[65536]; // 64 KiB buffer
            long position = 0;
            var seenSnapshots = new HashSet<Guid>();

            // Scan stream in 64 KiB chunks with 16 KiB overlap to catch block headers
            int overlap = 16384;

            while (position < streamLength)
            {
                if (ct.IsCancellationRequested) break;

                stream.Position = position;
                int bytesRead = stream.Read(buffer, 0, buffer.Length);
                if (bytesRead < 64) break;

                // Search for VSS identifier GUID or VSST magic
                for (int i = 0; i + 64 <= bytesRead; i += 512)
                {
                    bool isGuid = IsVssGuidAt(buffer, i);
                    bool isTable = IsVsstMagicAt(buffer, i);

                    if (isGuid || isTable)
                    {
                        long blockOffset = position + i;
                        var snapshot = ParseVssBlock(buffer, i, bytesRead - i, blockOffset);
                        if (snapshot != null && snapshot.SnapshotId != Guid.Empty && !seenSnapshots.Contains(snapshot.SnapshotId))
                        {
                            seenSnapshots.Add(snapshot.SnapshotId);
                            report.Snapshots.Add(snapshot);
                        }
                    }
                }

                if (bytesRead < buffer.Length) break;
                position += (buffer.Length - overlap);
            }

            FinalizeReport(report);
            return report;
        }

        public static VssReport ParseBuffer(byte[] buffer, string sourceName = null)
        {
            var report = new VssReport { SourcePath = sourceName ?? "Buffer" };
            if (buffer == null || buffer.Length < 64) return report;

            using (var ms = new MemoryStream(buffer))
            {
                return ScoutStream(ms, sourceName, CancellationToken.None);
            }
        }

        /// <summary>
        /// Parse a single VSS block header (Catalog or Store descriptor).
        /// </summary>
        public static VssSnapshotRecord ParseVssBlock(byte[] buffer, int offset, int length, long physicalOffset = 0)
        {
            if (buffer == null || offset < 0 || length < 64 || offset + 64 > buffer.Length) return null;

            // Offset 0x00: VSS identifier GUID (16 bytes)
            byte[] idBytes = new byte[16];
            Buffer.BlockCopy(buffer, offset, idBytes, 0, 16);

            // Offset 0x10: Version (uint32)
            uint version = BitConverter.ToUInt32(buffer, offset + 16);

            // Offset 0x14: Record type (uint32): 1 = Volume Header, 2 = Catalog 1, 3 = Catalog 2, 4 = Store Block Table
            uint recordType = BitConverter.ToUInt32(buffer, offset + 20);

            // Offset 0x18: Relative offset (uint64)
            ulong relOffset = BitConverter.ToUInt64(buffer, offset + 24);

            // Offset 0x20: Next relative offset (uint64)
            ulong nextRelOffset = BitConverter.ToUInt64(buffer, offset + 32);

            // If this is a Catalog Record (RecordType == 2 or 3):
            if (recordType == 2 || recordType == 3)
            {
                // Read catalog entries within the block
                // In Windows VSS Catalog block:
                // Offset 0x28: Entry type (uint32)
                // Offset 0x2C: Entry size (uint32)
                int cursor = offset + 40;
                while (cursor + 80 <= offset + length)
                {
                    uint entryType = BitConverter.ToUInt32(buffer, cursor);
                    uint entrySize = BitConverter.ToUInt32(buffer, cursor + 4);

                    if (entrySize < 64 || entrySize > 4096)
                    {
                        // Fallback: check fixed 128-byte stride
                        entrySize = 128;
                    }

                    // EntryType == 2 (Snapshot Entry) or EntryType == 3 (Application snapshot)
                    if (entryType == 2 || entryType == 3)
                    {
                        var snap = ParseSnapshotEntry(buffer, cursor, (int)entrySize, physicalOffset);
                        if (snap != null) return snap;
                    }

                    cursor += (int)entrySize;
                }
            }
            else if (recordType == 4)
            {
                // Store Block Table (Block Descriptors)
                var snap = new VssSnapshotRecord
                {
                    SnapshotId = Guid.NewGuid(),
                    Attributes = "Store Block Table (CoW Descriptor)",
                    IsCarved = true
                };

                int cursor = offset + 40;
                while (cursor + 16 <= offset + length && snap.BlockMappings.Count < 1000)
                {
                    ulong volOff = BitConverter.ToUInt64(buffer, cursor);
                    ulong storeOff = BitConverter.ToUInt64(buffer, cursor + 8);

                    if (volOff > 0 && storeOff > 0 && volOff < 0x7FFFFFFFFFFFFFFFUL)
                    {
                        snap.BlockMappings.Add(new VssBlockMapping
                        {
                            OriginalVolumeOffset = (long)volOff,
                            StoreOffset = (long)storeOff,
                            BlockLength = 16384
                        });
                    }
                    cursor += 16;
                }

                if (snap.BlockMappings.Count > 0)
                {
                    snap.StoreBlockCount = snap.BlockMappings.Count;
                    snap.AllocatedBytes = (long)snap.StoreBlockCount * 16384L;
                    return snap;
                }
            }

            // Direct snapshot record fallback:
            // Check if buffer contains a snapshot GUID followed by valid FILETIME at offset + 32..40
            for (int scan = offset + 16; scan + 48 <= offset + length; scan += 16)
            {
                long candidateFt = BitConverter.ToInt64(buffer, scan + 32);
                if (candidateFt >= MinValidFileTime && candidateFt <= MaxValidFileTime)
                {
                    byte[] snapIdBytes = new byte[16];
                    Buffer.BlockCopy(buffer, scan, snapIdBytes, 0, 16);
                    Guid snapId = new Guid(snapIdBytes);

                    byte[] snapSetBytes = new byte[16];
                    Buffer.BlockCopy(buffer, scan + 16, snapSetBytes, 0, 16);
                    Guid snapSetId = new Guid(snapSetBytes);

                    if (snapId != Guid.Empty)
                    {
                        var snap = new VssSnapshotRecord
                        {
                            SnapshotId = snapId,
                            SnapshotSetId = snapSetId,
                            CreationTimeUtc = DateTime.FromFileTimeUtc(candidateFt),
                            Attributes = "Persistent, Differential",
                            IsCarved = true
                        };
                        return snap;
                    }
                }
            }

            return null;
        }

        private static VssSnapshotRecord ParseSnapshotEntry(byte[] buffer, int offset, int length, long physicalOffset)
        {
            if (offset + 64 > buffer.Length) return null;

            // Offset 8: Snapshot ID (GUID, 16 bytes)
            byte[] snapIdBytes = new byte[16];
            Buffer.BlockCopy(buffer, offset + 8, snapIdBytes, 0, 16);
            Guid snapId = new Guid(snapIdBytes);

            // Offset 24: Snapshot Set ID (GUID, 16 bytes)
            byte[] snapSetBytes = new byte[16];
            Buffer.BlockCopy(buffer, offset + 24, snapSetBytes, 0, 16);
            Guid snapSetId = new Guid(snapSetBytes);

            // Offset 40: Snapshot Creation Timestamp (FILETIME, 8 bytes)
            long creationFt = BitConverter.ToInt64(buffer, offset + 40);
            DateTime creationUtc = DateTime.MinValue;
            try
            {
                if (creationFt >= MinValidFileTime && creationFt <= MaxValidFileTime)
                {
                    creationUtc = DateTime.FromFileTimeUtc(creationFt);
                }
            }
            catch { }

            // Offset 48: Volume size (uint64)
            long volumeSize = (long)BitConverter.ToUInt64(buffer, offset + 48);

            // Offset 56: Allocated store bytes / block count (uint64)
            long allocatedBytes = (long)BitConverter.ToUInt64(buffer, offset + 56);

            // Offset 64: Machine Name (if length >= 80)
            string machineName = "Local System";
            if (length >= 88 && offset + 88 <= buffer.Length)
            {
                string candidateName = Encoding.ASCII.GetString(buffer, offset + 64, 16).TrimEnd('\0', ' ');
                if (!string.IsNullOrEmpty(candidateName) && IsPrintableAscii(candidateName))
                {
                    machineName = candidateName;
                }
            }

            var record = new VssSnapshotRecord
            {
                SnapshotId = snapId,
                SnapshotSetId = snapSetId,
                CreationTimeUtc = creationUtc,
                VolumeSize = Math.Max(0, volumeSize),
                AllocatedBytes = Math.Max(0, allocatedBytes),
                StoreBlockCount = (int)(allocatedBytes > 0 ? (allocatedBytes / 16384L) : 0),
                MachineName = machineName,
                Attributes = "ClientAccessible, Persistent, Differential"
            };

            return record;
        }

        private static void FinalizeReport(VssReport report)
        {
            report.TotalSnapshots = report.Snapshots.Count;
            long totalBytes = 0;
            int totalBlocks = 0;

            foreach (var s in report.Snapshots)
            {
                totalBytes += s.AllocatedBytes;
                totalBlocks += s.StoreBlockCount > 0 ? s.StoreBlockCount : s.BlockMappings.Count;
            }

            report.TotalSnapshotBytes = totalBytes;
            report.TotalStoreBlocks = totalBlocks;

            // Anti-Forensics check:
            // If snapshots have carved status and suspicious traits, flag deletion
            int carvedCount = 0;
            foreach (var s in report.Snapshots)
            {
                if (s.IsCarved) carvedCount++;
            }

            if (carvedCount > 0 && report.TotalSnapshots > 0)
            {
                report.IsWipedOrOrphaned = true;
                report.SuspicionReason = string.Format("Found {0} orphaned or carved VSS snapshots indicative of Volume Shadow Copy deletion (T1490 Inhibit System Recovery).", carvedCount);
            }
        }

        private static bool IsVssGuidAt(byte[] buffer, int offset)
        {
            if (offset + 16 > buffer.Length) return false;
            for (int i = 0; i < 16; i++)
            {
                if (buffer[offset + i] != VssIdentifierGuid[i]) return false;
            }
            return true;
        }

        private static bool IsVsstMagicAt(byte[] buffer, int offset)
        {
            if (offset + 4 > buffer.Length) return false;
            for (int i = 0; i < 4; i++)
            {
                if (buffer[offset + i] != VssTableMagic[i]) return false;
            }
            return true;
        }

        private static bool IsPrintableAscii(string s)
        {
            foreach (char c in s)
            {
                if (c < 32 || c > 126) return false;
            }
            return true;
        }
    }
