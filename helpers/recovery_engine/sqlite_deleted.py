"""Conservative Telegram records in SQLite free space of static local copies.

Independent implementation of https://sqlite.org/fileformat2.html. A full row
is attributed only to a currently reachable messages_v2/messages_topics table
leaf and only when SQL mid/uid/date agree with a strict public Telegram TL
record. Absence from that table proves a surviving non-current row, not who
deleted it or why. Freelist pages have lost table ownership and yield fragments
only. No source is opened writable, attached, checkpointed or vacuumed.

For WAL copies the reader overlays the latest checksum-valid committed frame
for every modified page. Uncommitted frames never enter that view. Invalid WAL
tails fail closed; old main pages are never scanned as current free space.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from contextlib import nullcontext
import hashlib
from pathlib import Path
import re
import sqlite3
import struct

from sqlite_history import (HistoryError, HistoryLimits, _db_header, _parse_wal,
                            _safe_path as _history_path, _sha256 as _history_sha, _state)
from telegram_tl import PROFILES, TelegramTlError, parse_message


class DeletedError(ValueError):
    def __init__(self, code):
        self.code = code
        super().__init__(code)


class _OverflowPayload(ValueError):
    def __init__(self, payload_length):
        self.payload_length = payload_length
        super().__init__("overflow or truncated payload")


@dataclass(frozen=True, slots=True)
class DeletedLimits:
    max_input_bytes: int = 4 * 1024 * 1024 * 1024
    max_pages: int = 262144
    max_scan_bytes: int = 256 * 1024 * 1024
    max_candidates: int = 200000
    max_records: int = 20000
    max_output_bytes: int = 64 * 1024 * 1024
    max_sqlite_ops: int = 5_000_000


def _safe_path(*args, **kwargs):
    try:
        return _history_path(*args, **kwargs)
    except HistoryError as error:
        raise DeletedError(error.code) from None


def _sha256(path, cancel):
    try:
        return _history_sha(path, cancel)
    except HistoryError as error:
        raise DeletedError(error.code) from None


def _cancel(cancel):
    if cancel is not None and cancel():
        raise DeletedError("CANCELLED")


def _get_limits(limits):
    if limits is None:
        return DeletedLimits()
    if isinstance(limits, dict):
        try:
            limits = DeletedLimits(**limits)
        except TypeError as error:
            raise DeletedError("INVALID_LIMITS") from error
    if not isinstance(limits, DeletedLimits):
        raise DeletedError("INVALID_LIMITS")
    if any(type(getattr(limits, key)) is not int or not 0 < getattr(limits, key) <= cap
           for key, cap in asdict(DeletedLimits()).items()):
        raise DeletedError("INVALID_LIMITS")
    return limits


def _varint(data, offset, end):
    value = 0
    for index in range(9):
        if offset >= end:
            raise ValueError("varint bounds")
        number = data[offset]
        offset += 1
        if index == 8:
            return (value << 8) | number, offset
        value = (value << 7) | (number & 127)
        if number < 128:
            # Overlong encodings are not generated by supported SQLite files.
            if index and value < 1 << (7 * index):
                raise ValueError("noncanonical varint")
            return value, offset
    raise ValueError("varint")


def _serial_length(serial):
    if serial < 0 or serial in (10, 11):
        raise ValueError("reserved serial type")
    if serial < 12:
        return (0, 1, 2, 3, 4, 6, 8, 8, 0, 0)[serial]
    return (serial - (12 if serial % 2 == 0 else 13)) // 2


def _decode(serial, value, encoding):
    if serial == 0:
        return None
    if 1 <= serial <= 6:
        return int.from_bytes(value, "big", signed=True)
    if serial == 7:
        return struct.unpack(">d", value)[0]
    if serial in (8, 9):
        return serial - 8
    if serial >= 12:
        return bytes(value) if serial % 2 == 0 else bytes(value).decode(encoding, "strict")
    raise ValueError("serial type")


def _record(data, start, end, columns, encoding, *, damaged_length=False):
    """Read one complete inline SQL record; never invent field/body bytes.

    SQLite may replace the first four bytes of a freed cell with its linked
    freeblock header. If only the single record-header LENGTH byte was lost,
    it is derivable from all surviving serial types and the known column count.
    We never reconstruct an overwritten serial type, mid, uid, date or BLOB.
    """
    if damaged_length:
        at = start + 1
        header_end = None
    else:
        length, at = _varint(data, start, end)
        if length < len(columns) + 1 or length > 9 * len(columns) + 9 or length > end - start:
            raise ValueError("header size")
        header_end = start + length
    serials = []
    for index, column in enumerate(columns):
        serial, at = _varint(data, at, header_end or end)
        if column in ("mid", "uid", "date", "topic_id") and serial not in (1, 2, 3, 4, 5, 6, 8, 9):
            raise ValueError("numeric key required")
        if column == "data" and (serial < 12 or serial % 2):
            raise ValueError("BLOB required")
        serials.append(serial)
    if header_end is None:
        if at - start >= 128:
            raise ValueError("missing multibyte header")
        header_end = at
    elif at != header_end:
        raise ValueError("column count")
    size = sum(_serial_length(serial) for serial in serials)
    if size > end - header_end:
        raise _OverflowPayload(header_end - start + size)
    values, offsets = {}, {}
    at = header_end
    for column, serial in zip(columns, serials):
        length = _serial_length(serial)
        values[column] = _decode(serial, data[at:at + length], encoding)
        offsets[column] = at
        at += length
    return values, offsets, at, serials


def _overflow_payload(pages, data, number, location, start, end, length, free_leaves):
    """Follow only surviving pointers into validated, currently free leaves.

    The local-payload formula is SQLite fileformat2 section 1.6. No allocated
    page, freelist trunk, guessed continuation, padding or missing byte is used.
    A reconstructed header-length byte is left as found, as for inline rows.
    """
    usable = pages.usable
    maximum = usable - 35
    if length <= maximum:
        raise ValueError("truncated inline record")
    if length > pages.limits.max_output_bytes:
        pages.report["limited"] = True
        raise ValueError("overflow output limit")
    minimum = ((usable - 12) * 32 // 255) - 23
    proposed = minimum + (length - minimum) % (usable - 4)
    local = proposed if proposed <= maximum else minimum
    if local <= 0 or local + 4 > end - start:
        raise ValueError("missing local payload or overflow pointer")
    pointer = int.from_bytes(data[start + local:start + local + 4], "big")
    ranges = [{"logical_offset": 0, "bytes": local, "sqlite_page": number,
               "physical_source": location["physical_source"],
               "physical_byte_offset": location["physical_page_offset"] + start,
               "wal_frame": location["wal_frame"]}]
    parts, visited, remaining = [data[start:start + local]], set(), length - local
    while remaining:
        _cancel(pages.cancel)
        if pointer not in free_leaves or pointer in visited or pointer == number:
            raise ValueError("overflow page is not an unused leaf")
        if len(visited) >= min(pages.limits.max_pages, 4095):
            pages.report["limited"] = True
            raise ValueError("overflow page limit")
        take = min(remaining, usable - 4)
        if take + 4 > pages.limits.max_scan_bytes - pages.report["bytes_scanned"]:
            pages.report["limited"] = True
            raise ValueError("overflow scan limit")
        visited.add(pointer)
        payload, origin = pages.read(pointer)
        pages.report["bytes_scanned"] += take + 4
        pages.report["pages_scanned"] += 1
        parts.append(payload[4:4 + take])
        ranges.append({"logical_offset": length - remaining, "bytes": take,
                       "sqlite_page": pointer, "physical_source": origin["physical_source"],
                       "physical_byte_offset": origin["physical_page_offset"] + 4,
                       "wal_frame": origin["wal_frame"]})
        pointer = int.from_bytes(payload[:4], "big")
        remaining -= take
    if pointer:
        raise ValueError("overflow chain exceeds declared payload")
    return b"".join(parts), local, ranges


def _keys_match(row, value):
    if any(type(row.get(key)) is not int for key in ("mid", "uid", "date")):
        return False
    if row["mid"] != value["id"] or row["date"] != value["date"]:
        return False
    # Android secret-chat dialog identifiers use high 32 bits. The public
    # non-secret peer layouts below must never authorize their attribution.
    uid = row["uid"]
    if uid == 0 or uid & 0xffffffff == 0 or abs(uid) >= 1 << 52:
        return False
    peer, sender = value["peer"], value["from_peer"]
    if peer["kind"] in ("chat", "channel"):
        return uid == -peer["id"]
    if value["out"] or sender is None:
        return uid > 0 and uid == peer["id"]
    return uid > 0 and sender["kind"] == "user" and uid == sender["id"]


class _Pages:
    def __init__(self, source, wal, limits, cancel, report):
        self.source, self.wal = source, wal
        self.limits, self.cancel, self.report = limits, cancel, report
        source.seek(0)
        self.header = source.read(100)
        source.seek(0, 2)
        self.page_size = _db_header(self.header, source.tell())
        self.pages = source.tell() // self.page_size
        self.frames = {}
        self.commit = None
        if wal is not None:
            wal.seek(0, 2)
            size = wal.tell()
            if size > limits.max_input_bytes:
                raise DeletedError("DELETED_WAL_INPUT_LIMIT")
            wal.seek(0)
            wal_report = {}
            frames, commits = _parse_wal(wal, size, self.page_size,
                HistoryLimits(max_input_bytes=limits.max_input_bytes,
                              max_frames=limits.max_pages,
                              max_page_count=limits.max_pages), cancel, wal_report)
            if wal_report.get("tail_reason"):
                raise DeletedError("DELETED_WAL_INVALID_OR_LIMITED")
            if commits:
                self.commit = commits[-1]["frame"]
                self.pages = commits[-1]["pages"]
                self.frames = {frame.page: frame for frame in frames[:self.commit]}
            report.update(wal_commit_frame=self.commit,
                          uncommitted_frames_ignored=wal_report["uncommitted_frames"])
        if self.pages > limits.max_pages:
            raise DeletedError("DELETED_PAGE_LIMIT")
        self.header = self.read(1)[0][:100]
        self.usable = self.page_size - self.header[20]
        self.encoding = {1: "utf-8", 2: "utf-16-le", 3: "utf-16-be"}.get(int.from_bytes(self.header[56:60], "big"))
        if self.encoding is None:
            raise DeletedError("DELETED_ENCODING_INVALID")

    def read(self, number):
        _cancel(self.cancel)
        if not 1 <= number <= self.pages:
            raise DeletedError("DELETED_PAGE_BOUNDS")
        frame = self.frames.get(number)
        stream = self.wal if frame else self.source
        position = frame.data_offset if frame else (number - 1) * self.page_size
        stream.seek(position)
        payload = stream.read(self.page_size)
        if len(payload) != self.page_size:
            raise DeletedError("DELETED_PAGE_TRUNCATED")
        return payload, {"physical_source": "wal" if frame else "db",
                         "physical_page_offset": position,
                         "wal_frame": frame.number if frame else None}


def _leaf_regions(pages, number, payload):
    """Validate active cells/freeblocks; yield only inactive byte intervals."""
    header = 100 if number == 1 else 0
    if payload[header] != 13:
        raise DeletedError("DELETED_TABLE_PAGE_INVALID")
    count = int.from_bytes(payload[header + 3:header + 5], "big")
    pointers_end = header + 8 + count * 2
    content = int.from_bytes(payload[header + 5:header + 7], "big") or 65536
    if pointers_end > content or content > pages.usable:
        raise DeletedError("DELETED_TABLE_PAGE_INVALID")
    occupied = []
    for index in range(count):
        start = int.from_bytes(payload[header + 8 + index * 2:header + 10 + index * 2], "big")
        if not content <= start < pages.usable:
            raise DeletedError("DELETED_CELL_INVALID")
        length, at = _varint(payload, start, pages.usable)
        _, at = _varint(payload, at, pages.usable)
        usable = pages.usable
        minimum = ((usable - 12) * 32 // 255) - 23
        local = length if length <= usable - 35 else minimum + (length - minimum) % (usable - 4)
        if local > usable - 35:
            local = minimum
        end = at + local + (4 if length > local else 0)
        if end > usable:
            raise DeletedError("DELETED_CELL_INVALID")
        occupied.append((start, end))
    occupied.sort()
    if any(left[1] > right[0] for left, right in zip(occupied, occupied[1:])):
        raise DeletedError("DELETED_CELL_OVERLAP")
    blocks, visited = [], set()
    start = int.from_bytes(payload[header + 1:header + 3], "big")
    while start:
        if start in visited or not content <= start <= pages.usable - 4:
            raise DeletedError("DELETED_FREEBLOCK_INVALID")
        visited.add(start)
        following, size = struct.unpack_from(">HH", payload, start)
        end = start + size
        if size < 4 or end > pages.usable or following and following < end:
            raise DeletedError("DELETED_FREEBLOCK_INVALID")
        if any(start < right and end > left for left, right in occupied):
            raise DeletedError("DELETED_FREEBLOCK_LIVE_OVERLAP")
        blocks.append((start, end, "freeblock"))
        start = following
    if pointers_end < content:
        blocks.append((pointers_end, content, "unallocated"))
    return blocks


def _table_leaves(pages, root):
    pending, visited = [root], set()
    while pending:
        number = pending.pop()
        if number in visited:
            raise DeletedError("DELETED_BTREE_CYCLE")
        visited.add(number)
        if len(visited) > pages.limits.max_pages:
            raise DeletedError("DELETED_PAGE_LIMIT")
        data, location = pages.read(number)
        header = 100 if number == 1 else 0
        kind = data[header]
        if kind == 13:
            yield number, data, location
        elif kind == 5:
            count = int.from_bytes(data[header + 3:header + 5], "big")
            if header + 12 + count * 2 > pages.usable:
                raise DeletedError("DELETED_BTREE_INVALID")
            children = [int.from_bytes(data[header + 8:header + 12], "big")]
            for index in range(count):
                at = int.from_bytes(data[header + 12 + index * 2:header + 14 + index * 2], "big")
                if at < header + 12 + count * 2 or at + 5 > pages.usable:
                    raise DeletedError("DELETED_BTREE_INVALID")
                children.append(int.from_bytes(data[at:at + 4], "big"))
            pending.extend(children)
        else:
            raise DeletedError("DELETED_BTREE_UNSUPPORTED")


def _freelist(pages):
    expected = int.from_bytes(pages.header[36:40], "big")
    trunk = int.from_bytes(pages.header[32:36], "big")
    visited, leaves = set(), []
    while trunk:
        if trunk in visited or len(visited) >= pages.limits.max_pages:
            raise DeletedError("DELETED_FREELIST_INVALID")
        visited.add(trunk)
        data, _ = pages.read(trunk)
        following, count = struct.unpack_from(">II", data)
        if count > pages.usable // 4 - 2:
            raise DeletedError("DELETED_FREELIST_INVALID")
        for index in range(count):
            number = int.from_bytes(data[8 + index * 4:12 + index * 4], "big")
            if number in visited or not 1 <= number <= pages.pages:
                raise DeletedError("DELETED_FREELIST_INVALID")
            visited.add(number)
            leaves.append(number)
        trunk = following
    if len(visited) != expected:
        raise DeletedError("DELETED_FREELIST_COUNT")
    return leaves


def recover(db_path, *, connection=None, include_unattributed=False,
            limits=None, cancel=None, report=None):
    """Return bounded, verified residual rows/fragments with byte provenance.

    For a WAL pair provide the read-only connection to that *working copy*;
    otherwise this function uses immutable SQLite and creates no sidecars.
    No results are returned if source consistency fails at the final check.
    """
    limits = _get_limits(limits)
    report = {} if report is None else report
    report.clear()
    report.update(status="validating", limits=asdict(limits), pages_scanned=0,
                  bytes_scanned=0, candidates_checked=0, recovered_records=0,
                  previous_records=0, fragments=0, skipped_pages=[], limited=False)
    db = _safe_path(db_path, regular=True)
    wal_path = Path(str(db) + "-wal")
    wal_path = _safe_path(wal_path, regular=True) if wal_path.is_file() and wal_path.stat().st_size else None
    if db.stat().st_size > limits.max_input_bytes:
        raise DeletedError("DELETED_INPUT_LIMIT")
    if connection is None and wal_path is not None:
        raise DeletedError("DELETED_WAL_CONNECTION_REQUIRED")
    initial = {path: _state(path) for path in (db, wal_path) if path is not None}
    hashes = {path: _sha256(path, cancel) for path in initial}
    own = connection is None
    if own:
        connection = sqlite3.connect(db.as_uri() + "?mode=ro&immutable=1", uri=True)
        connection.enable_load_extension(False)
        connection.execute("PRAGMA trusted_schema=OFF")
    records, seen, output_bytes = [], set(), 0
    try:
        # The caller's SQLite connection must describe exactly the same copy
        # whose physical bytes and WAL pages are being inspected.
        main = next((row[2] for row in connection.execute("PRAGMA database_list") if row[1] == "main"), None)
        if main is None or Path(main).resolve() != db.resolve():
            raise DeletedError("DELETED_CONNECTION_MISMATCH")
        operations = 0
        def progress():
            nonlocal operations
            operations += 1000
            return int(operations > limits.max_sqlite_ops or cancel is not None and cancel())
        # Do not replace a caller's global progress handler. Individual lookups
        # use indexed, fixed identifiers; own connections get a local budget.
        if own:
            connection.set_progress_handler(progress, 1000)
        if connection.execute("PRAGMA quick_check(1)").fetchall() != [("ok",)]:
            raise DeletedError("DELETED_SQLITE_INVALID")
        tables = connection.execute("SELECT name,rootpage,sql FROM sqlite_master WHERE type='table' AND name IN ('messages_v2','messages_topics') ORDER BY name").fetchall()
        with db.open("rb") as source:
            with (wal_path.open("rb") if wal_path else nullcontext(None)) as wal:
                pages = _Pages(source, wal, limits, cancel, report)
                if connection.execute("PRAGMA page_count").fetchone()[0] != pages.pages:
                    raise DeletedError("DELETED_CURRENT_VIEW_MISMATCH")
                report.update(page_size=pages.page_size, db_sha256=hashes[db],
                              wal_sha256=hashes.get(wal_path), current_view="validated_committed_wal_overlay" if wal else "main_database")
                reachable = set()
                free_leaves = set(_freelist(pages))
                for table, root, sql in tables:
                    if not isinstance(sql, str) or not re.match(r"CREATE\s+TABLE\b", sql, re.I) or re.search(r"WITHOUT\s+ROWID", sql, re.I):
                        continue
                    info = connection.execute("PRAGMA table_info(" + table + ")").fetchall()
                    columns = [row[1] for row in info]
                    if not 4 <= len(columns) <= 128 or not {"mid", "uid", "date", "data"} <= set(columns):
                        continue
                    for number, data, location in _table_leaves(pages, root):
                        reachable.add(number)
                        report["pages_scanned"] += 1
                        try:
                            regions = _leaf_regions(pages, number, data)
                        except (DeletedError, ValueError) as error:
                            report["skipped_pages"].append({"page": number, "reason": getattr(error, "code", "DELETED_CELL_INVALID")})
                            continue
                        for begin, end, kind in regions:
                            if report["bytes_scanned"] + end - begin > limits.max_scan_bytes:
                                report["limited"] = True
                                break
                            report["bytes_scanned"] += end - begin
                            starts = [(at, False, end) for at in range(begin + (4 if kind == "freeblock" else 0), end)
                                      if len(columns) + 1 <= data[at] <= min(255, len(columns) * 9 + 9)]
                            if kind == "freeblock" and end - begin > 4:
                                # Adjacent deletions coalesce. SQLite leaves old
                                # four-byte freeblock headers inside the merged
                                # range; each may have lost only header length.
                                for prefix in range(begin, end - 4):
                                    following, amount = struct.unpack_from(">HH", data, prefix)
                                    if 8 <= amount <= end - prefix and (following == 0 or prefix + amount <= following <= pages.usable - 4):
                                        starts.append((prefix + 3, True, prefix + amount))
                            for at, damaged, record_limit in starts:
                                _cancel(cancel)
                                if report["candidates_checked"] >= limits.max_candidates:
                                    report["limited"] = True
                                    break
                                report["candidates_checked"] += 1
                                try:
                                    overflow = None
                                    try:
                                        row, offsets, record_end, serials = _record(data, at, record_limit, columns, pages.encoding, damaged_length=damaged)
                                    except _OverflowPayload as missing:
                                        payload, local, ranges = _overflow_payload(pages, data, number, location, at,
                                            record_limit, missing.payload_length, free_leaves)
                                        row, offsets, payload_end, serials = _record(payload, 0, len(payload), columns,
                                            pages.encoding, damaged_length=damaged)
                                        if payload_end != len(payload):
                                            raise ValueError("overflow payload length mismatch")
                                        offsets = {key: at + value if value < local else None for key, value in offsets.items()}
                                        record_end = at + local
                                        overflow = {"sqlite_payload_length": len(payload),
                                            "sqlite_payload_sha256": hashlib.sha256(payload).hexdigest(),
                                            "sqlite_payload_ranges": ranges,
                                            "sqlite_overflow_pages": [item["sqlite_page"] for item in ranges[1:]],
                                            "sqlite_overflow_chain_verified": True}
                                    value = parse_message(row["data"])
                                    if not _keys_match(row, value):
                                        continue
                                except (ValueError, OverflowError, UnicodeError):
                                    if report["limited"]:
                                        break
                                    continue
                                key = (table, row["uid"], row["mid"], row.get("topic_id"), hashlib.sha256(row["data"]).hexdigest())
                                if key in seen:
                                    continue
                                topic = " AND topic_id=?" if "topic_id" in columns else ""
                                parameters = (row["mid"], row["uid"], row["topic_id"]) if topic else (row["mid"], row["uid"])
                                current = connection.execute("SELECT date,data FROM " + table + " WHERE mid=? AND uid=?" + topic + " LIMIT 2", parameters).fetchall()
                                if any(entry[0] == row["date"] and entry[1] == row["data"] for entry in current):
                                    continue
                                size = record_end - at
                                output_size = overflow["sqlite_payload_length"] if overflow else size
                                if len(records) >= limits.max_records or output_size > limits.max_output_bytes - output_bytes:
                                    report["limited"] = True
                                    break
                                seen.add(key)
                                output_bytes += output_size
                                status = "previous_version_residual" if current else "deleted_supported_by_evidence"
                                result = {"table": table, "row": row, "value": value,
                                    "recovery_status": status, "deleted": None,
                                    "deletion_interpretation": "row_absent_from_current_table" if not current else "different_surviving_version_of_current_key",
                                    "sqlite_page": number, "sqlite_region": kind,
                                    "sqlite_record_page_offset": at, "sqlite_record_length": size,
                                    "sqlite_blob_page_offset": offsets["data"],
                                    "sqlite_header_length_reconstructed": damaged,
                                    "sqlite_record_sha256": hashlib.sha256(data[at:record_end]).hexdigest(),
                                    "byte_offset": (number - 1) * pages.page_size + at,
                                    "offset_kind": "sqlite_logical_file_byte",
                                    "physical_source": location["physical_source"],
                                    "physical_byte_offset": location["physical_page_offset"] + at,
                                    "wal_frame": location["wal_frame"], "wal_commit_frame": pages.commit,
                                    "proof": "reachable_table_free_space_and_sql_tl_key_agreement"}
                                if overflow:
                                    result.update(overflow)
                                    result["proof"] = "reachable_table_free_space_free_overflow_chain_and_sql_tl_key_agreement"
                                records.append(result)
                                report["previous_records" if current else "recovered_records"] += 1
                            if report["limited"]:
                                break
                        if report["limited"]:
                            break
                    if report["limited"]:
                        break
                if include_unattributed and not report["limited"]:
                    # A freelist leaf's former table is unknowable. Retained TL
                    # bytes may aid a keyword search but never become chat rows.
                    for number in _freelist(pages):
                        if number in reachable:
                            raise DeletedError("DELETED_FREELIST_LIVE_OVERLAP")
                        if report["bytes_scanned"] + pages.usable > limits.max_scan_bytes:
                            report["limited"] = True
                            break
                        data, location = pages.read(number)
                        report["pages_scanned"] += 1
                        report["bytes_scanned"] += pages.usable
                        for fragment in tl_fragments(data[:pages.usable], cancel=cancel):
                            if len(records) >= limits.max_records or fragment["byte_length"] > limits.max_output_bytes - output_bytes:
                                report["limited"] = True
                                break
                            fragment.update(sqlite_page=number, sqlite_region="freelist_leaf", table=None,
                                byte_offset=(number - 1) * pages.page_size + fragment["byte_offset"],
                                physical_source=location["physical_source"],
                                physical_byte_offset=location["physical_page_offset"] + fragment["byte_offset"],
                                wal_frame=location["wal_frame"], wal_commit_frame=pages.commit)
                            records.append(fragment)
                            output_bytes += fragment["byte_length"]
                            report["fragments"] += 1
                        if report["limited"]:
                            break
        for path, state in initial.items():
            if _state(path) != state or _sha256(path, cancel) != hashes[path]:
                raise DeletedError("DELETED_SOURCE_CHANGED")
        report.update(status="limited" if report["limited"] else "complete", output_bytes=output_bytes)
        return records
    except (HistoryError, sqlite3.DatabaseError) as error:
        _cancel(cancel)
        raise DeletedError(error.code if isinstance(error, HistoryError) else "DELETED_SQLITE_INVALID") from None
    finally:
        if own:
            connection.close()


_CONSTRUCTORS = re.compile(b"|".join(re.escape(struct.pack("<I", key)) for key in PROFILES))


def tl_fragments(data, *, cancel=None, limit=20000):
    """Strict public TL wire bodies, with *unconfirmed* SQL/account context."""
    count = 0
    for match in _CONSTRUCTORS.finditer(data):
        _cancel(cancel)
        try:
            value = parse_message(data[match.start():match.start() + 65536], allow_trailing=True)
        except (TelegramTlError, ValueError, OverflowError):
            continue
        if not value["text"]:
            continue
        length = value["consumed_bytes"]
        yield {"text": value["text"], "byte_offset": match.start(), "byte_length": length,
            "offset_kind": "file_byte", "encoding": "telegram_tl_utf8",
            "recovery_status": "unattributed_structured_fragment",
            "application_confirmed": True, "chat_id": None, "message_id": None,
            "sender_id": None, "timestamp": None, "deleted": None,
            "candidate_message_id": value["id"], "candidate_peer": value["peer"],
            "candidate_date": value["date"], "native_constructor": value["constructor"],
            "native_layer": value["layer"],
            "native_tl_body_sha256": hashlib.sha256(data[match.start():match.start() + length]).hexdigest(),
            "proof": "supported_tl_body_without_confirmed_table_or_account"}
        count += 1
        if count >= limit:
            return


def wal_fragments(wal_path, *, limits=None, cancel=None, report=None):
    """Typed fragments from superseded, committed checksum-valid WAL pages.

    A page's superseded version is not a full historical database. Consequently
    these findings keep real chat/message/sender/date unknown and carry only
    candidate TL fields. An earlier frame replaced within the same uncommitted
    transaction, or never reaching a commit, is never a committed preimage.
    """
    limits = _get_limits(limits)
    report = {} if report is None else report
    report.clear()
    report.update(status="validating", fragments=0, scanned_page_versions=0,
                  limited=False, tail_reason=None)
    path = _safe_path(wal_path, regular=True)
    initial = _state(path)
    if initial[2] > limits.max_input_bytes:
        raise DeletedError("DELETED_WAL_INPUT_LIMIT")
    before_hash = _sha256(path, cancel)
    records, output_bytes = [], 0
    try:
        with path.open("rb") as source:
            header = source.read(32)
            if len(header) != 32:
                raise DeletedError("DELETED_WAL_INVALID")
            page_size = int.from_bytes(header[8:12], "big")
            if not 512 <= page_size <= 65536 or page_size & (page_size - 1):
                raise DeletedError("DELETED_WAL_INVALID")
            source.seek(0)
            frames, commits = _parse_wal(source, initial[2], page_size,
                HistoryLimits(max_frames=limits.max_pages,
                              max_page_count=limits.max_pages), cancel, report)
            # The version visible at a commit is its latest frame at/before
            # that commit. Record exactly when each physical version was known
            # to be committed, without materializing a whole DB snapshot.
            current, committed, exposed = {}, {}, {}
            commit_by_frame = {item["frame"]: item for item in commits}
            for frame in frames:
                _cancel(cancel)
                current[frame.page] = frame
                if frame.number in commit_by_frame:
                    item = commit_by_frame[frame.number]
                    for page, version in current.items():
                        if page <= item["pages"]:
                            exposed.setdefault(version.number, item["frame"])
                    committed = {page: version for page, version in current.items() if page <= item["pages"]}
                    current = committed.copy()
            previous = [frame for frame in frames if frame.number in exposed and
                        frame.page in committed and committed[frame.page].number != frame.number]
            report.update(page_size=page_size, wal_sha256=before_hash,
                          committed_superseded_versions=len(previous))
            for frame in previous:
                if (report["scanned_page_versions"] + 1) * page_size > limits.max_scan_bytes:
                    report["limited"] = True
                    break
                source.seek(frame.data_offset)
                data = source.read(page_size)
                if len(data) != page_size:
                    raise DeletedError("DELETED_SOURCE_CHANGED")
                report["scanned_page_versions"] += 1
                for value in tl_fragments(data, cancel=cancel):
                    if len(records) >= limits.max_records or value["byte_length"] > limits.max_output_bytes - output_bytes:
                        report["limited"] = True
                        break
                    offset = value["byte_offset"]
                    value.update(physical_source="wal", physical_byte_offset=frame.data_offset + offset,
                        byte_offset=frame.data_offset + offset, offset_kind="wal_file_byte",
                        sqlite_page=frame.page, sqlite_region="superseded_committed_wal_page",
                        sqlite_record_page_offset=offset, wal_frame=frame.number,
                        wal_commit_frame=exposed[frame.number],
                        proof="validated_committed_wal_page_and_supported_tl_without_table_context")
                    records.append(value)
                    output_bytes += value["byte_length"]
                    report["fragments"] += 1
                if report["limited"]:
                    break
        if _state(path) != initial or _sha256(path, cancel) != before_hash:
            raise DeletedError("DELETED_SOURCE_CHANGED")
        report.update(status="limited" if report["limited"] else "validated_prefix" if report.get("tail_reason") else "complete",
                      output_bytes=output_bytes)
        return records
    except HistoryError as error:
        raise DeletedError(error.code) from None
